// Phase 11a — extend the built-in `users` auth collection.
//
// Domain fields (display_name, abbreviation, day_cutoff_hour,
// default_excursion_split_km, linked_person) replace the hardcoded
// constants we used in Phase 1. Auth options open up self-service
// registration via e-mail and password; OAuth2 is enabled at the
// collection level — actual Apple-OAuth2 provider keys are configured
// out-of-band via the PocketBase admin UI (Apple Service ID, Team ID,
// Key ID, Private Key).
//
// Rules:
//   - List: nil (admin-only — we don't expose a user list)
//   - View: only self
//   - Create: open (PocketBase enforces e-mail uniqueness + the
//     verification flow before granting access in higher-rules
//     collections later)
//   - Update / Delete: only self (so account deletion works without
//     admin intervention — App-Store-required)
//
// PocketBase 0.23 port: the 0.22 auth options map onto the typed
// collection options exactly as the 0.23 upgrade migration converts them
// (password auth with identity field `email`, OAuth2 off while no
// provider is configured, required email, password min length 8). A
// fresh 0.23+ `users` collection has no `username` field, an upgraded
// 0.22 one keeps it (required, autogenerated `users123456`); we add it
// here when missing so fresh and upgraded databases return the same
// record shape. Token lifetimes keep the 0.22 defaults (auth 14 days,
// verification 7 days) instead of the shorter 0.23 defaults.
package migrations

import (
	"github.com/pocketbase/pocketbase/core"
	m "github.com/pocketbase/pocketbase/migrations"
	"github.com/pocketbase/pocketbase/tools/types"
)

// 0.22 defaults the upgrade migration copies into upgraded databases.
const (
	legacyAuthTokenDuration         = 1209600 // 14 days
	legacyVerificationTokenDuration = 604800  // 7 days
	legacyUsernameIndex             = "CREATE UNIQUE INDEX `__pb_users_auth__username_idx` ON `users` (username COLLATE NOCASE)"
)

func init() {
	m.Register(func(app core.App) error {
		users, err := app.FindCollectionByNameOrId("users")
		if err != nil {
			return err
		}

		// Auth options (0.22: AllowEmailAuth, AllowOAuth2Auth without
		// providers, !AllowUsernameAuth, RequireEmail, MinPasswordLength 8,
		// !OnlyVerified). Verification is required for some flows but we
		// don't block login on it — many users will register, log in,
		// and then verify on the next session via the mail link.
		users.PasswordAuth.Enabled = true
		users.PasswordAuth.IdentityFields = []string{core.FieldNameEmail}
		users.OAuth2.Enabled = false
		users.AuthRule = types.Pointer("")
		users.AuthToken.Duration = legacyAuthTokenDuration
		users.VerificationToken.Duration = legacyVerificationTokenDuration
		if f, ok := users.Fields.GetByName(core.FieldNameEmail).(*core.EmailField); ok {
			f.Required = true
		}
		if f, ok := users.Fields.GetByName(core.FieldNamePassword).(*core.PasswordField); ok {
			f.Min = 8
		}
		ensureLegacyUsernameField(users)

		// Domain fields. None are required so OAuth2 sign-ups (where
		// the iOS-side Apple credentials may or may not include the
		// full name) still go through cleanly.
		users.Fields.Add(&core.TextField{Name: "display_name"})
		users.Fields.Add(&core.TextField{Name: "abbreviation"})
		users.Fields.Add(&core.NumberField{
			Name: "day_cutoff_hour",
			Min:  floatPtr(0),
			Max:  floatPtr(23),
		})
		users.Fields.Add(&core.NumberField{
			Name: "default_excursion_split_km",
			Min:  floatPtr(0),
		})

		// linked_person needs the people collection to exist already
		// (Phase 6). If we ever migrate from a fresh DB without
		// people, we tolerate the lookup failing.
		if people, err := app.FindCollectionByNameOrId("people"); err == nil {
			users.Fields.Add(&core.RelationField{
				Name:          "linked_person",
				CollectionId:  people.Id,
				CascadeDelete: false,
				MinSelect:     0,
				MaxSelect:     1,
			})
		}

		users.ListRule = nil
		users.ViewRule = types.Pointer("id = @request.auth.id")
		users.CreateRule = types.Pointer("")
		users.UpdateRule = types.Pointer("id = @request.auth.id")
		users.DeleteRule = types.Pointer("id = @request.auth.id")

		return app.Save(users)
	}, func(app core.App) error {
		users, err := app.FindCollectionByNameOrId("users")
		if err != nil {
			return err
		}
		removeFields(users,
			"display_name", "abbreviation", "day_cutoff_hour",
			"default_excursion_split_km", "linked_person",
		)
		// Reset auth options to the PocketBase defaults.
		users.PasswordAuth.IdentityFields = []string{core.FieldNameEmail}
		users.ListRule = nil
		users.ViewRule = nil
		users.CreateRule = nil
		users.UpdateRule = nil
		users.DeleteRule = nil
		return app.Save(users)
	})
}

// ensureLegacyUsernameField adds the `username` field (and its unique
// index) the 0.23 upgrade keeps on every 0.22 auth collection, with the
// exact settings of that upgrade.
func ensureLegacyUsernameField(users *core.Collection) {
	if users.Fields.GetByName("username") != nil {
		return
	}
	users.Fields.Add(&core.TextField{
		Id:                  "text4166911607", // fieldIdChecksum("text", "username") of the upgrade
		Name:                "username",
		Required:            true,
		Min:                 3,
		Max:                 150,
		Pattern:             `^[\w][\w\.\-]*$`,
		AutogeneratePattern: "users[0-9]{6}",
	})
	if users.GetIndex("__pb_users_auth__username_idx") == "" {
		users.Indexes = append(users.Indexes, legacyUsernameIndex)
	}
}

func floatPtr(f float64) *float64 { return &f }
